"""Build Appendix A (verbatim prompts and question definitions) from the code that ran the study.

    python paper_out/make_appendix.py   -> paper_out/appendix_A_prompts.md

Every prompt is imported from the module that used it, so the appendix cannot drift from the code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, ".")
sys.path.insert(0, "prereg")
import fidelity_audit as fa  # noqa: E402
import jev_arms as jarms  # noqa: E402
import jev_attributes as jattr  # noqa: E402
import positive_controls as pc  # noqa: E402
import style_mitigation as sm  # noqa: E402
from src.prompts import (PERSONA_REWRITE_SYSTEM, PERSONA_REWRITE_USER, PROMPT_VERSIONS,  # noqa: E402
                         REMEDY_DECISION_SYSTEM, REMEDY_DECISION_USER)

FENCE = "~~~"


def block(title: str, text: str) -> str:
    return f"**{title}**\n\n{FENCE}\n{text.strip()}\n{FENCE}\n"


def main() -> None:
    parts = ["# Appendix A. Prompts and question definitions (verbatim)\n",
             "Generated by `paper_out/make_appendix.py` from the modules that ran the study. "
             f"Prompt versions: `{json.dumps(PROMPT_VERSIONS)}`.\n",
             "## A.1 Remedy decision (GPT-4o-mini, GPT-5-mini)\n",
             block("System", REMEDY_DECISION_SYSTEM), block("User (the complaint is inserted at {narrative})", REMEDY_DECISION_USER),
             "## A.2 Persona rewrite (both rewrite banks)\n",
             block("System", PERSONA_REWRITE_SYSTEM), block("User template", PERSONA_REWRITE_USER),
             "## A.3 Jev remedy question (six option orders)\n",
             block("Question definition, primary order o012 (JSON)", json.dumps(jarms.order_questions(["o012"], with_persona=False), indent=2)),
             "## A.4 Jev attribute questions (19 attributes)\n",
             block("Question definitions (JSON)", json.dumps(jattr.build_attribute_questions(), indent=2)),
             "## A.5 Positive-control fact edits (GPT-4o-mini)\n",
             block("System", pc.EDIT_SYSTEM),
             block("Edit instructions (JSON)", json.dumps(pc.EDITS, indent=2)),
             "## A.6 Style standardisation (GPT-4o-mini, temperature 0)\n",
             block("System", sm.STYLE_SYSTEM),
             block("Style instructions (JSON)", json.dumps(sm.STYLES, indent=2)),
             "## A.7 Fact-fidelity auditor (Claude Opus 5.5, GPT-5.2)\n",
             block("System", fa.AUDIT_SYSTEM),
             block("Output schema (JSON)", json.dumps(fa.AUDIT_SCHEMA, indent=2))]
    Path("paper_out/appendix_A_prompts.md").write_text("\n".join(parts), encoding="utf-8")
    print("wrote paper_out/appendix_A_prompts.md")


if __name__ == "__main__":
    main()
